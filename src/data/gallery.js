const byId = Object.fromEntries(gallery.map((g) => [g.id, g]))

// Look up a photo URL by id; throws on a typo so a broken image shows up in dev.
export const img = (id) => {
  if (!byId[id]) throw new Error(`Unknown photo: ${id}`)
  return byId[id].src
}

